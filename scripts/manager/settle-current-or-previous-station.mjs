#!/usr/bin/env node
import { spawn } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs, readJson, writeJson } from './lib/manager-utils.mjs';
import { SupabaseRestClient } from './lib/supabase-rest.mjs';

const args = parseArgs();
const activeFile = args.active || 'data/manager/active_events.json';
const photoFile = args.photos || 'data/manager/player_photos.json';
const priceVersion = args['price-version'] || 1;
const priceStatus = args['price-status'] || 'draft';
const settledForDate = args['settled-for-date'] || '';

const here = path.dirname(fileURLToPath(import.meta.url));
const node = process.execPath;
const active = await readJson(activeFile);
const serviceReady = Boolean(process.env.SUPABASE_SERVICE_ROLE_KEY);

function script(name) {
  return path.join(here, name);
}

function run(label, argv) {
  return new Promise((resolve, reject) => {
    console.log(`\n== ${label} ==`);
    const child = spawn(node, argv, {
      cwd: process.cwd(),
      env: process.env,
      stdio: 'inherit'
    });
    child.on('error', reject);
    child.on('exit', (code) => {
      if (code === 0) resolve();
      else reject(new Error(`${label} exited with code ${code}`));
    });
  });
}

function refreshArgs(stationFile, extra = []) {
  return [
    script('refresh-current-station-data.mjs'),
    '--active', stationFile,
    '--photos', photoFile,
    '--price-version', String(priceVersion),
    '--price-status', String(priceStatus),
    ...extra
  ];
}

async function generatedPreviousActiveFile(previous) {
  if (!previous.publication_file) {
    throw new Error(`Previous station ${previous.station_key} is missing publication_file.`);
  }
  const publication = await readJson(`data/manager/${previous.publication_file}`);
  const stationConfig = publication?.snapshot?.station_config || {};
  const frozenRules = stationConfig.rules || {};
  const stationGrant = frozenRules.station_grant ?? stationConfig.station_grant ?? publication.station_grant;
  if (!Number.isFinite(Number(stationGrant))) {
    throw new Error(`Previous station ${previous.station_key} publication is missing station_grant.`);
  }
  const previousActive = {
    season: active.season,
    station_key: previous.station_key,
    station_name: previous.station_name || previous.station_key,
    survivor_aligned: active.survivor_aligned,
    status: 'settling_previous',
    updated_at: new Date().toISOString(),
    notes: [
      'Generated by settle-current-or-previous-station.mjs.',
      'Used only for continuing settlement while the previous station has unfinished finals.',
      `Rules restored from ${previous.publication_file}.`
    ],
    rules: {
      ...frozenRules,
      station_grant: Number(stationGrant),
      combo_version: frozenRules.combo_version || stationConfig.combo_version || publication.combo_version || 'classic',
      combo: frozenRules.combo || stationConfig.combo || {}
    },
    events: (previous.events || []).map((event) => ({ ...event, active: true }))
  };
  const outFile = `outputs/manager-sync/${previous.station_key}-active-events.json`;
  await writeJson(outFile, previousActive);
  return outFile;
}

async function refreshAndSettle(stationFile, stationKey, label) {
  await run(`${label}: sync latest results`, refreshArgs(stationFile, [
    '--write',
    '--sync',
    '--skip-draw'
  ]));

  const settleExtra = ['--skip-draw', '--skip-schedule', '--sync', '--settle'];
  if (settledForDate) settleExtra.push('--settled-for-date', settledForDate);
  await run(`${label}: settle`, refreshArgs(stationFile, settleExtra));

  const report = await readJson(`outputs/manager-sync/${stationKey}-current-station-data.json`);
  return report.settlement_result || null;
}

function finalsComplete(result) {
  const eventCount = Number(result && result.event_count);
  const finalsCompleted = Number(result && result.finals_completed);
  return eventCount > 0 && finalsCompleted >= eventCount;
}

function resultLabel(result) {
  if (!result) return 'no settlement result';
  return `settlements=${result.settlements || 0} points_delta=${result.points_delta || 0} combo_lineups=${result.combo_lineups || 0} finals=${result.finals_completed || 0}/${result.event_count || 0}`;
}

async function previousAlreadySettled(previous) {
  if (!serviceReady) return false;
  try {
    const client = new SupabaseRestClient({ dryRun: false });
    const rows = await client.select('tour_manager_events', {
      select: 'event_key,market_status',
      station_key: `eq.${previous.station_key}`,
      season: `eq.${active.season}`
    });
    const liveRows = rows.filter((row) => row.market_status !== 'cancelled');
    return liveRows.length > 0 && liveRows.every((row) => row.market_status === 'settled');
  } catch (error) {
    console.log(`WARN Could not check previous station settled status: ${error.message}`);
    return false;
  }
}

if (!serviceReady) {
  console.log('WARN SUPABASE_SERVICE_ROLE_KEY is missing; child refresh scripts will write local reports only.');
}

const previous = active.previous_station;
if (previous && previous.station_key && Array.isArray(previous.events) && previous.events.length) {
  if (await previousAlreadySettled(previous)) {
    console.log(`Previous station ${previous.station_key} is already settled; continue with current station.`);
  } else {
    const previousFile = await generatedPreviousActiveFile(previous);
    const previousResult = await refreshAndSettle(previousFile, previous.station_key, `previous station ${previous.station_key}`);
    console.log(`Previous station settlement: ${resultLabel(previousResult)}`);

    if (!finalsComplete(previousResult)) {
      console.log(`Previous station ${previous.station_key} is not fully complete; skip current station settlement for now.`);
      process.exit(0);
    }
  }
}

const currentResult = await refreshAndSettle(activeFile, active.station_key, `current station ${active.station_key}`);
console.log(`Current station settlement: ${resultLabel(currentResult)}`);
